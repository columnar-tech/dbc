const (
	lockFileVersionV2  = 2
	lockSourceRegistry = "registry"
	lockHashPrefix     = "sha256:"
	lockFileHeaderV2   = "This file is automatically @generated by dbc. Not intended for manual editing"
	lockUnsupportedFmt = "unsupported lock file version %d; this version of dbc supports lock file versions %d and %d"
	lockNewerDbcNeeded = "unsupported lock file version %d; a newer version of dbc is required to read this file"
)

var (
	lockHashRE   = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)
	lockTargetRE = regexp.MustCompile(`^[a-z0-9]+(_[a-z0-9]+)+$`)
)

type lockedSource struct {
	Type string `toml:"type"`
	URL  string `toml:"url"`
}

// lockedArtifact locates one archive. Exactly one of Path (relative to the
// source registry) or URL (absolute) must be present; presence is decided by
// key presence so that an empty string is not treated as absent.
type lockedArtifact struct {
	Target string  `toml:"target"`
	Path   *string `toml:"path,omitempty"`
	URL    *string `toml:"url,omitempty"`
	Hash   string  `toml:"hash"`
}

type lockedDriver struct {
	Name      string           `toml:"name"`
	Version   string           `toml:"version"`
	Source    lockedSource     `toml:"source"`
	Artifacts []lockedArtifact `toml:"artifacts"`
}

type lockFileV2 struct {
	Version int            `toml:"version" comment:"This file is automatically @generated by dbc. Not intended for manual editing"`
	Drivers []lockedDriver `toml:"drivers"`
}

// parsedLockFile holds the result of readLockFile; only the field matching
// Version is populated.
type parsedLockFile struct {
	Version int
	V1      LockFile
	V2      lockFileV2
}

// canonicalRegistryIdentity returns the credential-free identity of a
// registry base URL: lowercase scheme and host, no userinfo, query or
// fragment, and no trailing slash.
func canonicalRegistryIdentity(u *url.URL) (string, error) {
	if u == nil {
		return "", errors.New("registry URL is missing")
	}
	scheme := strings.ToLower(u.Scheme)
	if (scheme != "http" && scheme != "https") || u.Host == "" || u.Opaque != "" {
		return "", errors.New("registry URL must be an absolute http or https URL with a host")
	}
	p := strings.TrimRight(u.EscapedPath(), "/")
	return scheme + "://" + strings.ToLower(u.Host) + p, nil
}

func validateRegistryIdentity(s string) error {
	u, err := url.Parse(s)
	if err != nil {
		return fmt.Errorf("invalid registry identity: %w", err)
	}
	canon, err := canonicalRegistryIdentity(u)
	if err != nil {
		return err
	}
	if canon != s || u.User != nil || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" {
		return fmt.Errorf("registry identity %q is not canonical (expected %q)", s, canon)
	}
	return nil
}

func validateLockedPath(p string) error {
	if p == "" {
		return errors.New("path is empty")
	}
	if strings.ContainsAny(p, "\\?#") {
		return fmt.Errorf("path %q contains a forbidden character", p)
	}
	if strings.HasPrefix(p, "/") {
		return fmt.Errorf("path %q must be relative", p)
	}
	u, err := url.Parse(p)
	if err != nil {
		return fmt.Errorf("path %q is not a valid relative URL path: %w", p, err)
	}
	if u.Scheme != "" || u.Host != "" || u.Opaque != "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" {
		return fmt.Errorf("path %q must be a plain relative path", p)
	}
	for seg := range strings.SplitSeq(p, "/") {
		dec, err := url.PathUnescape(seg)
		if err != nil {
			return fmt.Errorf("path %q has an invalid escape: %w", p, err)
		}
		if seg == "" || dec == "" || dec == "." || dec == ".." || strings.ContainsAny(dec, "/\\") {
			return fmt.Errorf("path %q has a forbidden segment", p)
		}
	}
	return nil
}

func validateLockedURL(s string) error {
	u, err := url.Parse(s)
	if err != nil {
		return errors.New("url is not valid")
	}
	scheme := strings.ToLower(u.Scheme)
	if (scheme != "http" && scheme != "https") || u.Host == "" || u.Opaque != "" {
		return errors.New("url must be an absolute http or https URL with a host")
	}
	if u.User != nil || u.RawQuery != "" || u.ForceQuery || u.Fragment != "" || strings.ContainsAny(s, "?#") {
		return errors.New("url must not contain userinfo, query or fragment")
	}
	return nil
}

func lockedLocation(src lockedSource, a lockedArtifact) string {
	if a.URL != nil {
		return *a.URL
	}
	return src.URL + "/" + *a.Path
}

// strictDecodeError adds the offending keys to go-toml's generic strict-mode error.
func strictDecodeError(err error) error {
	var sme *toml.StrictMissingError
	if errors.As(err, &sme) {
		return fmt.Errorf("%w\n%s", err, sme.String())
	}
	return err
}

func (lf lockFileV2) validate() error {
	if lf.Version != lockFileVersionV2 {
		return fmt.Errorf("lock file version must be %d, got %d", lockFileVersionV2, lf.Version)
	}
	names := map[string]bool{}
	hashes := map[string]string{}
	for _, d := range lf.Drivers {
		if d.Name == "" {
			return errors.New("lock file contains a driver with an empty name")
		}
		if names[d.Name] {
			return fmt.Errorf("lock file contains duplicate driver %q", d.Name)
		}
		names[d.Name] = true
		v, err := semver.NewVersion(d.Version)
		if err != nil || v.String() != d.Version {
			return fmt.Errorf("driver %q has a non-canonical or invalid version %q", d.Name, d.Version)
		}
		if d.Source.Type != lockSourceRegistry {
			return fmt.Errorf("driver %q has unknown source type %q", d.Name, d.Source.Type)
		}
		if err := validateRegistryIdentity(d.Source.URL); err != nil {
			return fmt.Errorf("driver %q: source url: %w", d.Name, err)
		}
		if len(d.Artifacts) == 0 {
			return fmt.Errorf("driver %q has no artifacts", d.Name)
		}
		targets := map[string]bool{}
		for _, a := range d.Artifacts {
			if a.Target == "" || !lockTargetRE.MatchString(a.Target) {
				return fmt.Errorf("driver %q has an empty or malformed target %q", d.Name, a.Target)
			}
			if targets[a.Target] {
				return fmt.Errorf("driver %q has duplicate target %q", d.Name, a.Target)
			}
			targets[a.Target] = true
			if (a.Path == nil) == (a.URL == nil) {
				return fmt.Errorf("driver %q target %q must have exactly one of path or url", d.Name, a.Target)
			}
			if a.Path != nil {
				if err := validateLockedPath(*a.Path); err != nil {
					return fmt.Errorf("driver %q target %q: %w", d.Name, a.Target, err)
				}
			} else if err := validateLockedURL(*a.URL); err != nil {
				return fmt.Errorf("driver %q target %q: %w", d.Name, a.Target, err)
			}
			if !lockHashRE.MatchString(a.Hash) {
				return fmt.Errorf("driver %q target %q has a malformed hash; expected %s followed by 64 lowercase hex characters", d.Name, a.Target, lockHashPrefix)
			}
			loc := lockedLocation(d.Source, a)
			if prev, ok := hashes[loc]; ok && prev != a.Hash {
				return fmt.Errorf("location %s appears with different hashes", loc)
			}
			hashes[loc] = a.Hash
		}
	}
	return nil
}

// readLockFile reads a lock file of any supported version. Version 1 files
// are decoded exactly as before; version 2 files are decoded strictly and
// validated.
func readLockFile(path string) (parsedLockFile, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return parsedLockFile{}, fmt.Errorf("error opening lock file %s: %w", path, err)
	}
	var hdr struct {
		Version int `toml:"version"`
	}
	if err := toml.Unmarshal(data, &hdr); err != nil {
		return parsedLockFile{}, fmt.Errorf("error decoding lock file %s: %w", path, err)
	}
	switch hdr.Version {
	case lockFileVersion:
		lf, err := loadLockFile(path)
		if err != nil {
			return parsedLockFile{}, err
		}
		return parsedLockFile{Version: lockFileVersion, V1: lf}, nil
	case lockFileVersionV2:
		var lf lockFileV2
		dec := toml.NewDecoder(bytes.NewReader(data)).DisallowUnknownFields()
		if err := dec.Decode(&lf); err != nil {
			return parsedLockFile{}, fmt.Errorf("error decoding lock file %s: %w", path, strictDecodeError(err))
		}
		if err := lf.validate(); err != nil {
			return parsedLockFile{}, fmt.Errorf("invalid lock file %s: %w", path, err)
		}
		return parsedLockFile{Version: lockFileVersionV2, V2: lf}, nil
	default:
		if hdr.Version > lockFileVersionV2 {
			return parsedLockFile{}, fmt.Errorf(lockNewerDbcNeeded, hdr.Version)
		}
		return parsedLockFile{}, fmt.Errorf(lockUnsupportedFmt, hdr.Version, lockFileVersion, lockFileVersionV2)
	}
}

// writeLockFileV2 validates lf, sorts it deterministically and writes it
// atomically.
func writeLockFileV2(path string, lf lockFileV2) error {
	if err := lf.validate(); err != nil {
		return fmt.Errorf("refusing to write invalid lock file: %w", err)
	}
	out := lockFileV2{Version: lf.Version, Drivers: make([]lockedDriver, len(lf.Drivers))}
	for i, d := range lf.Drivers {
		d.Artifacts = append([]lockedArtifact(nil), d.Artifacts...)
		sort.Slice(d.Artifacts, func(a, b int) bool { return d.Artifacts[a].Target < d.Artifacts[b].Target })
		out.Drivers[i] = d
	}
	sort.Slice(out.Drivers, func(a, b int) bool { return out.Drivers[a].Name < out.Drivers[b].Name })
	data, err := toml.Marshal(out)
	if err != nil {
		return fmt.Errorf("error encoding lock file: %w", err)
	}
	return atomicfile.WriteFilePreservingMode(path, data, 0o644)
}

// newLockedArtifact records where resolved (the request URL produced by the
// package resolution for a registry rooted at base) can be found again. If
// the URL is reproducible from base it is stored as a registry-relative
// path; otherwise it is stored as an absolute URL, which must be free of
// userinfo, query and fragment.
func newLockedArtifact(base, resolved *url.URL, target, hash string) (lockedArtifact, error) {
	a := lockedArtifact{Target: target, Hash: hash}
	if rel, ok := relativeToBase(base, resolved); ok {
		if err := validateLockedPath(rel); err != nil {
			return a, fmt.Errorf("cannot record artifact location: %w", err)
		}
		a.Path = &rel
		return a, nil
	}
	if resolved.User != nil || resolved.RawQuery != "" || resolved.ForceQuery || resolved.Fragment != "" {
		return a, errors.New("cannot record artifact location: the URL contains userinfo, query or fragment and cannot be stored safely")
	}
	s := resolved.String()
	if err := validateLockedURL(s); err != nil {
		return a, fmt.Errorf("cannot record artifact location: %w", err)
	}
	a.URL = &s
	return a, nil
}

func sameOrigin(a, b *url.URL) bool {
	return strings.EqualFold(a.Scheme, b.Scheme) && strings.EqualFold(a.Host, b.Host)
}

// rootedPath returns the escaped path of u with a leading slash; JoinPath on
// a URL with an empty path yields a path without one.
func rootedPath(u *url.URL) string {
	p := u.EscapedPath()
	if !strings.HasPrefix(p, "/") {
		p = "/" + p
	}
	return p
}

// relativeToBase returns the escaped path of resolved relative to base when
// base.JoinPath(rel) would reproduce resolved exactly.
func relativeToBase(base, resolved *url.URL) (string, bool) {
	if !sameOrigin(base, resolved) || base.User.String() != resolved.User.String() ||
		base.RawQuery != resolved.RawQuery || base.ForceQuery != resolved.ForceQuery || resolved.Fragment != "" {
		return "", false
	}
	prefix := strings.TrimRight(rootedPath(base), "/") + "/"
	rel, ok := strings.CutPrefix(rootedPath(resolved), prefix)
	if !ok || rel == "" {
		return "", false
	}
	return rel, true
}

// boundRegistry is a configured registry matched to a locked identity. The
// BaseURL may carry credentials and a query and must only be used to issue
// requests, never to be printed or stored.
type boundRegistry struct {
	BaseURL  *url.URL
	HasQuery bool
}

func bindLockedRegistry(identity string, registries []dbc.Registry) (boundRegistry, error) {
	var matches []dbc.Registry
	for _, r := range registries {
		if r.BaseURL == nil {
			continue
		}
		if id, err := canonicalRegistryIdentity(r.BaseURL); err == nil && id == identity {
			matches = append(matches, r)
		}
	}
	switch len(matches) {
	case 0:
		return boundRegistry{}, fmt.Errorf("the lock file refers to registry %s, which is not configured; add it to your registry configuration", identity)
	case 1:
		b := matches[0].BaseURL
		return boundRegistry{BaseURL: b, HasQuery: b.RawQuery != "" || b.ForceQuery}, nil
	default:
		return boundRegistry{}, fmt.Errorf("the lock file refers to registry %s, which is ambiguous: it matches %d configured registries", identity, len(matches))
	}
}

// artifactURL returns the URL to request for a locked artifact.
func (b boundRegistry) artifactURL(a lockedArtifact) (*url.URL, error) {
	if (a.Path == nil) == (a.URL == nil) {
		return nil, errors.New("locked artifact must have exactly one of path or url")
	}
	if a.URL != nil {
		if err := validateLockedURL(*a.URL); err != nil {
			return nil, err
		}
		return url.Parse(*a.URL)
	}
	if err := validateLockedPath(*a.Path); err != nil {
		return nil, err
	}
	u := b.BaseURL.JoinPath(*a.Path)
	prefix := strings.TrimRight(rootedPath(b.BaseURL), "/") + "/"
	if !sameOrigin(b.BaseURL, u) || !strings.HasPrefix(rootedPath(u), prefix) {
		return nil, fmt.Errorf("locked path %q escapes the registry", *a.Path)
	}
	return u, nil
}
