func TestNewLockedArtifact(t *testing.T) {
	tests := []struct {
		name     string
		base     string
		resolved func(base *url.URL) *url.URL
		wantPath string
		wantURL  string
		wantErr  bool
	}{
		{"relative index url", "https://r.example.com", func(b *url.URL) *url.URL { return b.JoinPath("d/v1/x.tar.gz") }, "d/v1/x.tar.gz", "", false},
		{"default filename", "https://r.example.com", func(b *url.URL) *url.URL {
			return b.JoinPath("duckdb", "2.0.0", "duckdb_linux_amd64-2.0.0.tar.gz")
		}, "duckdb/2.0.0/duckdb_linux_amd64-2.0.0.tar.gz", "", false},
		{"absolute on same base", "https://r.example.com/", func(b *url.URL) *url.URL { return testURL(t, "https://R.example.com/pkgs/x.tar.gz") }, "pkgs/x.tar.gz", "", false},
		{"absolute other host", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://other.example.com/x.tar.gz") }, "", "https://other.example.com/x.tar.gz", false},
		{"absolute other scheme", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "http://r.example.com/x.tar.gz") }, "", "http://r.example.com/x.tar.gz", false},
		{"absolute other port", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://r.example.com:8443/x.tar.gz") }, "", "https://r.example.com:8443/x.tar.gz", false},
		{"prefix base", "https://host/mount/", func(b *url.URL) *url.URL { return b.JoinPath("d/x.tar.gz") }, "d/x.tar.gz", "", false},
		{"outside prefix", "https://host/mount/", func(b *url.URL) *url.URL { return testURL(t, "https://host/mountain/x.tar.gz") }, "", "https://host/mountain/x.tar.gz", false},
		{"outside prefix sibling", "https://host/mount", func(b *url.URL) *url.URL { return testURL(t, "https://host/other/x.tar.gz") }, "", "https://host/other/x.tar.gz", false},
		{"userinfo and query base", "https://u:SUPERSECRET@host/mount?token=SUPERSECRET", func(b *url.URL) *url.URL { return b.JoinPath("d/x.tar.gz") }, "d/x.tar.gz", "", false},
		{"absolute with query", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://r.example.com/x.tar.gz?sig=1") }, "", "", true},
		{"absolute with query other host", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://o.example.com/x.tar.gz?sig=1") }, "", "", true},
		{"absolute with userinfo other host", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://u:p@o.example.com/x.tar.gz") }, "", "", true},
		{"absolute with fragment", "https://r.example.com", func(b *url.URL) *url.URL { return testURL(t, "https://r.example.com/x.tar.gz#f") }, "", "", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			base := testURL(t, tt.base)
			resolved := tt.resolved(base)
			a, err := newLockedArtifact(base, resolved, "linux_amd64", testHashA)
			if tt.wantErr {
				require.Error(t, err)
				assert.NotContains(t, err.Error(), "SUPERSECRET")
				return
			}
			require.NoError(t, err)
			if tt.wantPath != "" {
				require.NotNil(t, a.Path)
				assert.Nil(t, a.URL)
				assert.Equal(t, tt.wantPath, *a.Path)
			} else {
				require.NotNil(t, a.URL)
				assert.Nil(t, a.Path)
				assert.Equal(t, tt.wantURL, *a.URL)
			}

			// Replay through rebinding reproduces the original request URL.
			id, err := canonicalRegistryIdentity(base)
			require.NoError(t, err)
			assert.NotContains(t, id, "SUPERSECRET")
			if a.Path != nil {
				assert.NotContains(t, *a.Path, "SUPERSECRET")
			}
			b, err := bindLockedRegistry(id, []dbc.Registry{{BaseURL: base}})
			require.NoError(t, err)
			got, err := b.artifactURL(a)
			require.NoError(t, err)
			assert.Equal(t, strings.ToLower(resolved.String()), strings.ToLower(got.String()))
		})
	}
}

func TestBindLockedRegistry(t *testing.T) {
	reg := func(s string) dbc.Registry { return dbc.Registry{Name: s, BaseURL: testURL(t, s)} }
	const id = "https://r.example.com/m"

	t.Run("one match", func(t *testing.T) {
		b, err := bindLockedRegistry(id, []dbc.Registry{reg("https://other.example.com"), reg("https://U:pw@R.example.com/m/?a=b")})
		require.NoError(t, err)
		assert.Equal(t, "https://U:pw@R.example.com/m/?a=b", b.BaseURL.String())
		assert.True(t, b.HasQuery)

		b, err = bindLockedRegistry(id, []dbc.Registry{reg("https://r.example.com/m")})
		require.NoError(t, err)
		assert.False(t, b.HasQuery)
	})

	t.Run("none", func(t *testing.T) {
		_, err := bindLockedRegistry(id, []dbc.Registry{reg("https://other.example.com")})
		require.ErrorContains(t, err, id)
		assert.ErrorContains(t, err, "not configured")
	})

	t.Run("ambiguous and order independent", func(t *testing.T) {
		a := reg("https://user:SUPERSECRET@r.example.com/m")
		b := reg("https://r.example.com/m?token=SUPERSECRET")
		for _, regs := range [][]dbc.Registry{{a, b}, {b, a}} {
			_, err := bindLockedRegistry(id, regs)
			require.ErrorContains(t, err, "ambiguous")
			assert.NotContains(t, err.Error(), "SUPERSECRET")
		}
	})

	t.Run("order does not change result", func(t *testing.T) {
		a, b := reg("https://r.example.com/m?token=SUPERSECRET"), reg("https://other.example.com")
		r1, err := bindLockedRegistry(id, []dbc.Registry{a, b})
		require.NoError(t, err)
		r2, err := bindLockedRegistry(id, []dbc.Registry{b, a})
		require.NoError(t, err)
		assert.Equal(t, r1.BaseURL.String(), r2.BaseURL.String())
	})

	t.Run("no secrets in none error", func(t *testing.T) {
		_, err := bindLockedRegistry(id, []dbc.Registry{reg("https://u:SUPERSECRET@x.example.com?token=SUPERSECRET")})
		require.Error(t, err)
		assert.NotContains(t, err.Error(), "SUPERSECRET")
	})
}

func TestArtifactURLRejectsEscapes(t *testing.T) {
	b := boundRegistry{BaseURL: testURL(t, "https://r.example.com/m")}
	for _, p := range []string{"../x", "%2e%2e/x", "//evil/x", "https:foo"} {
		_, err := b.artifactURL(lockedArtifact{Path: strp(p)})
		assert.Error(t, err, p)
	}
	_, err := b.artifactURL(lockedArtifact{})
	assert.Error(t, err)
	u, err := b.artifactURL(lockedArtifact{URL: strp("https://elsewhere.example.com/x")})
	require.NoError(t, err)
	assert.Equal(t, "https://elsewhere.example.com/x", u.String())
}

func TestLockedArtifactEscapedRoundTrip(t *testing.T) {
	bases := []string{
		"https://r.example.com",
		"https://r.example.com/mount/",
		"https://u:SUPERSECRET@r.example.com/mount?token=SUPERSECRET",
	}
	rels := []string{"a%20b/c.tar.gz", "d/x%2Bplus.tar.gz", "d/%E3%81%82/x.tar.gz"}
	for _, bs := range bases {
		for _, rel := range rels {
			t.Run(bs+" "+rel, func(t *testing.T) {
				base := testURL(t, bs)
				// Resolve the way pkginfo.GetPackage does for a relative index URL.
				resolved := base.JoinPath(rel)
				a, err := newLockedArtifact(base, resolved, "linux_amd64", testHashA)
				require.NoError(t, err)
				require.NotNil(t, a.Path)
				assert.Equal(t, rel, *a.Path)

				id, err := canonicalRegistryIdentity(base)
				require.NoError(t, err)
				b, err := bindLockedRegistry(id, []dbc.Registry{{BaseURL: base}})
				require.NoError(t, err)
				got, err := b.artifactURL(a)
				require.NoError(t, err)
				assert.Equal(t, resolved.String(), got.String())
			})
		}
	}
}
