func TestReadLockFileVersions(t *testing.T) {
	dir := t.TempDir()
	write := func(s string) string {
		p := filepath.Join(dir, "dbc.lock")
		require.NoError(t, os.WriteFile(p, []byte(s), 0o644))
		return p
	}

	got, err := readLockFile(write("version = 1\n[[drivers]]\nname = 'x'\nversion = '1.0.0'\n"))
	require.NoError(t, err)
	assert.Equal(t, 1, got.Version)
	assert.Equal(t, "1.0.0", got.V1.lockinfo["x"].Version.String())

	got, err = readLockFile(write("version = 2\n"))
	require.NoError(t, err)
	assert.Empty(t, got.V2.Drivers)

	_, err = readLockFile(write("version = 3\n"))
	assert.ErrorContains(t, err, "newer version of dbc")
	_, err = readLockFile(write("[[drivers]]\nname = 'x'\n"))
	assert.ErrorContains(t, err, "unsupported lock file version 0")

	_, err = readLockFile(filepath.Join(dir, "missing.lock"))
	assert.True(t, errors.Is(err, fs.ErrNotExist))
}

