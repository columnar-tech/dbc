func validV2() lockFileV2 {
	return lockFileV2{Version: 2, Drivers: []lockedDriver{{
		Name: "duckdb", Version: "2.0.0",
		Source: lockedSource{Type: "registry", URL: "https://dbc-cdn.columnar.tech"},
		Artifacts: []lockedArtifact{
			artifact("linux_amd64", resolution.ArtifactLocationRegistryPath, "duckdb/v2.0.0/x.tar.gz", testHashA),
			artifact("macos_arm64", resolution.ArtifactLocationURL, "https://example.com/x.tar.gz", testHashB),
		},
	}}}
}

func artifact(tuple string, kind resolution.ArtifactLocationKind, value, hash string) lockedArtifact {
	target, _ := resolution.TargetFromPlatformTuple(tuple)
	return lockedArtifact{Target: target, Format: "tar.gz", Location: resolution.ArtifactLocation{Kind: kind, Value: value}, Hash: hash}
}

func int64p(n int64) *int64 { return &n }

func TestLockFileV2RoundTrip(t *testing.T) {
	lf := validV2()
	lf.Drivers[0].Artifacts[0].Size = int64p(123)
	lf.Drivers[0].Artifacts[0].HostRequirements = resolution.HostRequirements{
		OSMin: "10.15", GLibCMin: "2.17", Libs: []string{"libc.so.6"},
		Bins: []resolution.NamedRequirement{{Name: "openssl", Min: "3.0"}},
	}
	lf.Drivers[0].Evidence = []resolution.Evidence{{
		Kind:     resolution.EvidenceKindReleaseMetadata,
		Location: resolution.ArtifactLocation{Kind: resolution.ArtifactLocationURL, Value: "https://example.com/release.json"},
		Hash:     testHashA,
	}}
	lf.Drivers = append(lf.Drivers, lockedDriver{
		Name: "arrow", Version: "1.0.0",
		Source: lockedSource{Type: "registry", URL: "https://dbc-cdn.columnar.tech"},
		Artifacts: []lockedArtifact{
			artifact("windows_amd64", resolution.ArtifactLocationRegistryPath, "b/w.tar.gz", testHashA),
			artifact("linux_amd64", resolution.ArtifactLocationRegistryPath, "b/l.tar.gz", testHashA),
		},
	})
	p := filepath.Join(t.TempDir(), "dbc.lock")
	require.NoError(t, writeLockFileV2(p, lf))
	first, err := os.ReadFile(p)
	require.NoError(t, err)
	assert.True(t, strings.HasPrefix(string(first), "# This file is automatically @generated by dbc."))
	assert.Less(t, strings.Index(string(first), "arrow"), strings.Index(string(first), "duckdb"))
	assert.Less(t, strings.Index(string(first), "b/l.tar.gz"), strings.Index(string(first), "b/w.tar.gz"))

	got, err := readLockFile(p)
	require.NoError(t, err)
	assert.Equal(t, 2, got.Version)
	require.Len(t, got.V2.Drivers[1].Artifacts, 2)
	// Driver ordering is deterministic (arrow precedes duckdb).
	duck := got.V2.Drivers[1]
	require.NotNil(t, duck.Artifacts[0].Size)
	assert.EqualValues(t, 123, *duck.Artifacts[0].Size)
	assert.Equal(t, lf.Drivers[0].Artifacts[0].HostRequirements, duck.Artifacts[0].HostRequirements)
	assert.Equal(t, lf.Drivers[0].Evidence, duck.Evidence)
	require.NoError(t, writeLockFileV2(p, got.V2))
	second, err := os.ReadFile(p)
	require.NoError(t, err)
	assert.Equal(t, string(first), string(second))
}

