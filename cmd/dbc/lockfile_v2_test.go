func TestCanonicalRegistryIdentity(t *testing.T) {
	tests := []struct{ in, want string }{
		{"https://dbc-cdn.columnar.tech", "https://dbc-cdn.columnar.tech"},
		{"HTTPS://DBC-CDN.Columnar.Tech/", "https://dbc-cdn.columnar.tech"},
		{"https://host/mount/", "https://host/mount"},
		{"https://user:pw@host:8443/m?token=x#frag", "https://host:8443/m"},
		{"http://host/a/b//", "http://host/a/b"},
		{"ftp://host", ""},
		{"https:///path", ""},
		{"/relative", ""},
		{"mailto:a@b", ""},
	}
	for _, tt := range tests {
		t.Run(tt.in, func(t *testing.T) {
			got, err := canonicalRegistryIdentity(testURL(t, tt.in))
			if tt.want == "" {
				assert.Error(t, err)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
			require.NoError(t, validateRegistryIdentity(got))
		})
	}
	_, err := canonicalRegistryIdentity(nil)
	assert.Error(t, err)
}

