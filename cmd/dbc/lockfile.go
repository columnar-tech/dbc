const (
	lockFileVersionV1 = 1
	lockFileVersion   = 2
)

// LockFile is the normalized in-memory form of supported lockfile versions.
// Version 1 entries are retained as legacy library proofs until a source has
// resolved the corresponding archive metadata.
type LockFile struct {
	Version  int        `toml:"version" comment:"This file is automatically @generated by dbc. Not intended for manual editing"`
	Revision int        `toml:"revision"`
	Drivers  []lockInfo `toml:"drivers"`

	lockinfo map[string]lockInfo `toml:"-"`
}

type lockInfo struct {
	Name      string              `toml:"name"`
	Version   *semver.Version     `toml:"version"`
	Source    lockSource          `toml:"source"`
	Evidence  []lockEvidence      `toml:"evidence,omitempty"`
	Artifacts []lockArtifact      `toml:"artifacts,omitempty"`
	Legacy    *legacyLibraryProof `toml:"legacy,omitempty"`
	// These fields are transient adapters for the current sync pipeline. They
	// are populated only while reading a v1 lock and are never serialized.
	Platform string `toml:"-"`
	Checksum string `toml:"-"`
}

type lockSource struct {
	Type    string `toml:"type"`
	Project string `toml:"project,omitempty"`
	URL     string `toml:"url,omitempty"`
	Path    string `toml:"path,omitempty"`
}

type lockEvidence struct {
	Kind     resolution.EvidenceKind     `toml:"kind"`
	Location resolution.ArtifactLocation `toml:"location"`
	Hash     string                      `toml:"hash"`
}

type lockArtifact struct {
	Target           resolution.Target           `toml:"target"`
	Format           string                      `toml:"format,omitempty"`
	Location         resolution.ArtifactLocation `toml:"location"`
	Hash             string                      `toml:"hash"`
	Size             *int64                      `toml:"size"`
	HostRequirements lockHostRequirements        `toml:"host_requirements,omitempty"`
}

type lockHostRequirements struct {
	OSMin    string                 `toml:"os_min,omitempty"`
	GLibCMin string                 `toml:"glibc_min,omitempty"`
	Libs     []string               `toml:"libs,omitempty"`
	Bins     []lockNamedRequirement `toml:"bins,omitempty"`
}

type lockNamedRequirement struct {
	Name string `toml:"name"`
	Min  string `toml:"min,omitempty"`
}

// legacyLibraryProof is deliberately distinct from lockArtifact.Hash: v1
// stored the hash of the installed shared library, not the archive.
type legacyLibraryProof struct {
	Platform    string `toml:"platform"`
	LibraryHash string `toml:"library_hash"`
}

type lockFileHeader struct {
	Version *int `toml:"version"`
}

type lockFileV1 struct {
	Version int            `toml:"version"`
	Drivers []lockDriverV1 `toml:"drivers"`
}

type lockDriverV1 struct {
	Name     string          `toml:"name"`
	Version  *semver.Version `toml:"version"`
	Platform string          `toml:"platform,omitempty"`
	Checksum string          `toml:"checksum,omitempty"`
}

type lockFileV2 LockFile

func loadLockFile(p string) (LockFile, error) {
	var lf LockFile
	data, err := os.ReadFile(p)
	if err != nil {
		return lf, fmt.Errorf("error opening lock file %s: %w", p, err)
	}

	var header lockFileHeader
	if err := toml.Unmarshal(data, &header); err != nil {
		return lf, fmt.Errorf("error decoding lock file %s: %w", p, err)
	}
	if header.Version == nil {
		return lf, fmt.Errorf("error decoding lock file %s: missing version", p)
	}

	switch *header.Version {
	case lockFileVersionV1:
		var wire lockFileV1
		if err := toml.Unmarshal(data, &wire); err != nil {
			return lf, fmt.Errorf("error decoding lock file %s: %w", p, err)
		}
		lf, err = normalizeLockFileV1(wire)
		if err != nil {
			return LockFile{}, fmt.Errorf("invalid lock file %s: %w", p, err)
		}
	case lockFileVersion:
		var wire lockFileV2
		if err := toml.Unmarshal(data, &wire); err != nil {
			return lf, fmt.Errorf("error decoding lock file %s: %w", p, err)
		}
		lf = LockFile(wire)
		if err := validateLockFileV2(lf); err != nil {
			return LockFile{}, fmt.Errorf("invalid lock file %s: %w", p, err)
		}
	default:
		return lf, fmt.Errorf("unsupported lock file version %d", *header.Version)
	}

	lf.indexDrivers()
	return lf, nil
}

func normalizeLockFileV1(wire lockFileV1) (LockFile, error) {
	lf := LockFile{Version: lockFileVersionV1}
	seenNames := make(map[string]struct{}, len(wire.Drivers))
	for i, old := range wire.Drivers {
		if old.Name == "" {
			return LockFile{}, fmt.Errorf("driver %d has no name", i)
		}
		if _, exists := seenNames[old.Name]; exists {
			return LockFile{}, fmt.Errorf("duplicate driver %q", old.Name)
		}
		seenNames[old.Name] = struct{}{}
		if old.Version == nil {
			return LockFile{}, fmt.Errorf("driver %q has no version", old.Name)
		}
		driver := lockInfo{Name: old.Name, Version: old.Version}
		if (old.Platform == "") != (old.Checksum == "") {
			return LockFile{}, fmt.Errorf("driver %d must have both platform and checksum or neither", i)
		}
		if old.Platform != "" && old.Checksum != "" {
			if err := validateLegacyLibraryHash(old.Checksum); err != nil {
				return LockFile{}, fmt.Errorf("driver %q has invalid v1 checksum: %w", old.Name, err)
			}
			driver.Legacy = &legacyLibraryProof{Platform: old.Platform, LibraryHash: old.Checksum}
			driver.Platform = old.Platform
			driver.Checksum = old.Checksum
		}
		lf.Drivers = append(lf.Drivers, driver)
	}
	return lf, nil
}

func (d lockInfo) legacyChecksumFor(platform string) string {
	if d.Legacy == nil || !samePlatformTarget(d.Legacy.Platform, platform) {
		return ""
	}
	return d.Legacy.LibraryHash
}

func (lf *LockFile) indexDrivers() {
	lf.lockinfo = make(map[string]lockInfo, len(lf.Drivers))
	for _, driver := range lf.Drivers {
		lf.lockinfo[driver.Name] = driver
	}
}

func validateLockFileV2(lf LockFile) error {
	if lf.Version != lockFileVersion {
		return fmt.Errorf("expected lock file version %d, got %d", lockFileVersion, lf.Version)
	}
	if lf.Revision < 0 {
		return fmt.Errorf("lock file revision must not be negative")
	}
	seenDrivers := make(map[string]struct{}, len(lf.Drivers))
	for i, driver := range lf.Drivers {
		if driver.Name == "" {
			return fmt.Errorf("driver %d has no name", i)
		}
		if _, exists := seenDrivers[driver.Name]; exists {
			return fmt.Errorf("duplicate driver %q", driver.Name)
		}
		seenDrivers[driver.Name] = struct{}{}
		if driver.Version == nil {
			return fmt.Errorf("driver %q has no version", driver.Name)
		}
		if err := validateLockInfo(driver); err != nil {
			return fmt.Errorf("driver %q: %w", driver.Name, err)
		}
	}
	return nil
}

func validateLockSource(source lockSource) error {
	if source.Type == "" {
		return fmt.Errorf("missing type")
	}
	switch source.Type {
	case "packslip":
		if source.Project == "" {
			return fmt.Errorf("packslip source has no project")
		}
		if _, err := sourceidentity.Parse(sourceidentity.Packslip, source.Project); err != nil {
			return err
		}
		if source.URL != "" || source.Path != "" {
			return fmt.Errorf("packslip source contains fields for another source type")
		}
	case "registry":
		if source.URL == "" {
			return fmt.Errorf("registry source has no URL")
		}
		if _, err := sourceidentity.Parse(sourceidentity.Registry, source.URL); err != nil {
			return err
		}
		if source.Project != "" || source.Path != "" {
			return fmt.Errorf("registry source contains fields for another source type")
		}
	case "path":
		if _, err := sourceidentity.Parse(sourceidentity.Path, source.Path); err != nil {
			return err
		}
		if source.Project != "" || source.URL != "" {
			return fmt.Errorf("path source contains fields for another source type")
		}
	default:
		return fmt.Errorf("unsupported source type %q", source.Type)
	}
	return nil
}

func parsePlatformTuple(platform string) (osName, arch, libc, variant string, ok bool) {
	target, err := resolution.TargetFromPlatformTuple(platform)
	if err != nil {
		return "", "", "", "", false
	}
	return target.OS, target.Arch, target.LibC, target.Variant, true
}

func targetIdentity(target resolution.Target) string {
	return strings.Join([]string{target.OS, target.Arch, target.LibC, target.Variant}, "\x00")
}

func samePlatformTarget(left, right string) bool {
	leftTarget, leftErr := resolution.TargetFromPlatformTuple(left)
	rightTarget, rightErr := resolution.TargetFromPlatformTuple(right)
	if leftErr != nil || rightErr != nil {
		return left == right
	}
	return leftTarget == rightTarget
}

func validateLegacyLibraryHash(hash string) error {
	if len(hash) != 64 {
		return fmt.Errorf("installed-library checksum must contain 64 lowercase hexadecimal characters")
	}
	for _, ch := range hash {
		if (ch < '0' || ch > '9') && (ch < 'a' || ch > 'f') {
			return fmt.Errorf("installed-library checksum must contain 64 lowercase hexadecimal characters")
		}
	}
	return nil
}

func checksum(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", fmt.Errorf("error opening file %s for checksum: %w", path, err)
	}
	defer f.Close()
	return checksumFile(f, path)
}

func checksumFile(file *os.File, path string) (string, error) {
	if _, err := file.Seek(0, io.SeekStart); err != nil {
		return "", fmt.Errorf("error seeking file %s for checksum: %w", path, err)
	}
	h := sha256.New()
	if _, err := io.Copy(h, file); err != nil {
		return "", fmt.Errorf("error calculating checksum for file %s: %w", path, err)
	}
	if _, err := file.Seek(0, io.SeekStart); err != nil {
		return "", fmt.Errorf("error rewinding file %s after checksum: %w", path, err)
	}

	return fmt.Sprintf("%x", h.Sum(nil)), nil
}
