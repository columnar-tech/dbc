// dbc_install installs driver name at the target and verifies its signature
// unless flags has DBC_INSTALL_ALLOW_UNSIGNED.
//
//export dbc_install
func dbc_install(client *C.dbc_client, name *C.char, kind C.dbc_target_kind, directory *C.char, flags C.dbc_install_flags, out **C.dbc_list, err_out **C.dbc_error) (status C.dbc_status) {
	defer recoverInto(err_out, &status)
	if out == nil {
		return fail(err_out, errNullOut)
	}
	c := objectAt[*clientObj](unsafe.Pointer(client))
	if c == nil {
		return fail(err_out, errBadObject)
	}
	target, err := targetFor(int32(kind), optString(directory))
	if err != nil {
		return fail(err_out, err)
	}
	opts, err := installOptions(int32(flags))
	if err != nil {
		return fail(err_out, err)
	}
	m, err := api.Install(context.Background(), c.client, C.GoString(name), target, opts)
	if err != nil {
		return fail(err_out, err)
	}
	return returnList(out, manifestList(m))
}

//export dbc_uninstall
func dbc_uninstall(name *C.char, kind C.dbc_target_kind, directory *C.char, err_out **C.dbc_error) (status C.dbc_status) {
	defer recoverInto(err_out, &status)
	target, err := targetFor(int32(kind), optString(directory))
	if err != nil {
		return fail(err_out, err)
	}
	if err := api.Uninstall(C.GoString(name), target); err != nil {
		return fail(err_out, err)
	}
	return C.DBC_OK
}

