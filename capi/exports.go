// dbc_client_new creates a client from count key/value option pairs (keys and
// values may be NULL when count is 0); see the option list in the preamble.
//
//export dbc_client_new
func dbc_client_new(keys, values **C.char, count C.size_t, out **C.dbc_client, err_out **C.dbc_error) (status C.dbc_status) {
	defer recoverInto(err_out, &status)
	if out == nil {
		return fail(err_out, errNullOut)
	}
	n := int(count)
	k, v := make([]string, n), make([]string, n)
	if n > 0 {
		ks, vs := unsafe.Slice(keys, n), unsafe.Slice(values, n)
		for i := range n {
			k[i], v[i] = C.GoString(ks[i]), C.GoString(vs[i])
		}
	}
	cfg, err := clientConfig(k, v)
	if err != nil {
		return fail(err_out, err)
	}
	c, err := api.NewClient(cfg, nil)
	if err != nil {
		return fail(err_out, err)
	}
	*out = (*C.dbc_client)(newObject(&clientObj{client: c}))
	return C.DBC_OK
}

