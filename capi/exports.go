// fail stores err in *err_out when err_out is non-NULL and returns DBC_ERROR.
func fail(err_out **C.dbc_error, err error) C.dbc_status {
	if err_out != nil {
		*err_out = (*C.dbc_error)(newObject(newErrorObj(err)))
	}
	return C.DBC_ERROR
}

// recoverInto turns a Go panic into DBC_ERROR, because unwinding into the C
// caller would abort the host process. Deferred by every dbc_status function.
func recoverInto(err_out **C.dbc_error, status *C.dbc_status) {
	if r := recover(); r != nil {
		*status = fail(err_out, fmt.Errorf("dbc: internal error: %v", r))
	}
}

// optString maps a C NULL to nil.
func optString(p *C.char) *string {
	if p == nil {
		return nil
	}
	s := C.GoString(p)
	return &s
}

// returnList hands l to the caller through out.
func returnList(out **C.dbc_list, l *listObj) C.dbc_status {
	*out = (*C.dbc_list)(newObject(l))
	return C.DBC_OK
}

