//! Raw FFI bindings to dbc's C API (`capi/` in github.com/columnar-tech/dbc),
//! generated by bindgen from the cgo-generated `libdbc.h`, whose preamble
//! documents ownership and error conventions. Use the `columnar-dbc` crate
//! instead of calling these directly.
//!
//! # Linking a system libdbc
//!
//! The default `bundled` feature links a prebuilt static library from a
//! platform crate. To use an installed libdbc without downloading the platform
//! crates, disable default features and enable `pkg-config`:
//!
//! ```toml
//! [dependencies]
//! columnar-dbc-sys = { version = "0", default-features = false, features = ["pkg-config"] }
//! ```
//!
//! Install the `libdbc-dev` (Debian/Ubuntu) or `libdbc-devel` (RPM) development
//! package, which provides `libdbc.a`, `libdbc.so`, `libdbc.h`, and `dbc.pc`.
//! For a downloaded Debian package, use `sudo apt install ./libdbc-dev_*.deb`.
//! The `pkg-config` executable must also be installed; set `PKG_CONFIG_PATH`
//! to the directory containing `dbc.pc` for a nonstandard prefix.
//!
//! The library source is selected in this order:
//!
//! 1. `DBC_SYS_LIB_DIR` selects a custom library directory.
//! 2. The `pkg-config` feature or the presence of `DBC_SYS_USE_PKG_CONFIG`
//!    selects the `dbc` pkg-config module.
//! 3. The `bundled` feature selects the prebuilt platform library.
//! 4. With none of these, the build fails.
//!
//! Environment overrides take precedence even when `bundled` is enabled.
//! System/custom linking is static by default; a custom directory must contain
//! `libdbc.a`. Set `DBC_DYNAMIC` to any value (including an empty string) to
//! select dynamic system/custom linking instead. Bundled linking always stays
//! static. Dynamic linking requires the shared library (`libdbc.so` on Linux)
//! on the runtime loader's search path, for example via `LD_LIBRARY_PATH`;
//! the crate does not configure that path.
#![no_std]

// Rust only links a dependency's native libraries if the crate is used, so
// reference platform crates only when the build script selects bundled linking.
#[cfg(all(dbc_bundled, target_os = "linux", target_arch = "x86_64", target_env = "gnu"))]
extern crate columnar_dbc_sys_linux_x64 as _;
#[cfg(all(dbc_bundled, target_os = "linux", target_arch = "aarch64", target_env = "gnu"))]
extern crate columnar_dbc_sys_linux_arm64 as _;
#[cfg(all(dbc_bundled, target_os = "macos", target_arch = "x86_64"))]
extern crate columnar_dbc_sys_darwin_x64 as _;
#[cfg(all(dbc_bundled, target_os = "macos", target_arch = "aarch64"))]
extern crate columnar_dbc_sys_darwin_arm64 as _;
#[cfg(all(dbc_bundled, target_os = "windows", target_arch = "x86_64"))]
extern crate columnar_dbc_sys_windows_x64 as _;

#[allow(non_camel_case_types)]
mod bindings;
pub use bindings::*;

/// Starts the Go runtime under the MSVC CRT.
///
/// A Go c-archive registers its runtime entry point in `.ctors`. The MinGW CRT
/// runs that section, but the MSVC CRT does not. Without this, the first dbc
/// call blocks forever in `_cgo_wait_runtime_init_done`. `.CRT$XCU` is the
/// MSVC CRT's C++ static-initializer table. rustc emits an undefined reference
/// to each `#[used]` static, which forces this object out of the rlib and into
/// the link.
#[cfg(dbc_msvc_go_init)]
mod msvc_runtime_init {
    extern "C" {
        fn _rt0_amd64_windows_lib();
    }

    #[used]
    #[link_section = ".CRT$XCU"]
    static START_GO_RUNTIME: unsafe extern "C" fn() = _rt0_amd64_windows_lib;
}
