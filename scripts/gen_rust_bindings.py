"""Regenerate rust/columnar-dbc-sys/src/bindings.rs from the cgo-generated libdbc.h.

Usage:
  CGO_ENABLED=1 go build -tags netgo,osusergo -buildmode=c-archive -o /tmp/capi/libdbc.a ./capi
  python3 scripts/gen_rust_bindings.py /tmp/capi/libdbc.h

Requires bindgen-cli 0.73.2 (cargo install bindgen-cli --version 0.73.2 --locked)
and libclang. CI regenerates on every target and fails on any difference.
"""

import pathlib
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "rust" / "columnar-dbc-sys" / "src" / "bindings.rs"
BINDGEN_VERSION = "0.73.2"
ARGS = [
    "--allowlist-function", "dbc_.*",
    "--allowlist-type", "dbc_.*",
    "--allowlist-var", "DBC_.*",
    # dbc_status/dbc_target_kind are int32_t; keep their constants i32 too.
    "--default-macro-constant-type", "signed",
    "--use-core",
    "--no-layout-tests",
    "--rust-target", "1.82",
]
LICENSE = """\
// Copyright 2026 Columnar Technologies Inc.
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// Generated by scripts/gen_rust_bindings.py from the cgo-generated libdbc.h.
// Do not edit.

"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    version = subprocess.run(["bindgen", "--version"], capture_output=True, text=True,
                             check=True).stdout.split()[-1]
    if version != BINDGEN_VERSION:
        print(f"error: bindgen {BINDGEN_VERSION} required, found {version}", file=sys.stderr)
        return 1
    generated = subprocess.run(["bindgen", sys.argv[1], *ARGS], capture_output=True,
                               text=True, check=True).stdout
    OUT.write_text(LICENSE + generated, newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
